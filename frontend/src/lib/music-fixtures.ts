export type PlayOrder = "sequence" | "single" | "shuffle";

export interface MusicLyricLine {
  /** 该行开始演唱的时间点（秒） */
  time: number;
  text: string;
}

export interface MusicTrack {
  id: string;
  title: string;
  artist: string;
  /** 总时长（秒） */
  duration: number;
  /** 唱片盘面与歌单缩略图的 CSS background：渐变或 url(...) 图片 */
  cover: string;
  lyrics: MusicLyricLine[];
}

/** 秒 → "m:ss"，播放器进度与歌单时长共用 */
export function formatDuration(seconds: number): string {
  const minutes = Math.floor(seconds / 60);
  const rest = Math.floor(seconds % 60);
  return `${minutes}:${rest.toString().padStart(2, "0")}`;
}

/** 当前唱到第几行：最后一个 time ≤ elapsed 的行；还没到第一行时返回 -1 */
export function findActiveLine(
  lyrics: MusicLyricLine[],
  elapsed: number,
): number {
  let active = -1;
  for (let index = 0; index < lyrics.length; index += 1) {
    if (lyrics[index].time > elapsed) break;
    active = index;
  }
  return active;
}

